#!/usr/bin/env ruby
# frozen_string_literal: true

# Writes lib/dommy/encodings/tables.rb from the Encoding Standard's own data:
#
#   encodings.json          https://encoding.spec.whatwg.org/encodings.json
#   index-<name>.txt        https://encoding.spec.whatwg.org/index-<name>.txt
#                           for each legacy single-byte encoding, and for
#                           jis0208, jis0212, big5, euc-kr and gb18030
#
# Usage: ruby script/build_encoding_tables.rb <dir with those files>
#
# It also writes lib/dommy/encodings/multibyte_overrides.rb. The multi-byte
# decoders read each index through a Ruby encoding
# (LegacyIndexes.ruby_lookup); that file records the pointers where the
# spec's index says otherwise — another code point, or none (runs of those
# as ranges).
#
# ISO-8859-8-I has no index file of its own; the spec says it shares
# index ISO-8859-8.

require "json"

dir = ARGV[0] or abort "Usage: #{$PROGRAM_NAME} <dir>"
table = JSON.parse(File.read(File.join(dir, "encodings.json")))

labels = {}
single_byte = []
table.each do |section|
  section["encodings"].each do |encoding|
    encoding["labels"].each { |label| labels[label] = encoding["name"] }
    single_byte << encoding["name"] if section["heading"] == "Legacy single-byte encodings"
  end
end

def read_index(path)
  index = Array.new(128)
  File.foreach(path) do |line|
    next if line.start_with?("#") || line.strip.empty?

    pointer, code_point = line.split("\t")
    index[pointer.to_i] = code_point.hex
  end
  index
end

indexes = single_byte.to_h do |name|
  file = name == "ISO-8859-8-I" ? "index-iso-8859-8.txt" : "index-#{name.downcase}.txt"
  [name, read_index(File.join(dir, file))]
end

out = +<<~RUBY
  # frozen_string_literal: true

  # Generated by script/build_encoding_tables.rb from the Encoding Standard's
  # encodings.json and index-*.txt. Do not edit by hand.
  #
  # Spec: https://encoding.spec.whatwg.org/

  module Dommy
    module Encodings
      # Every label the spec knows, lowercased, to the name of its encoding.
      LABELS = {
RUBY
labels.each { |label, name| out << "      #{label.inspect} => #{name.inspect},\n" }
# `<<~` strips the block's common indentation, which for a block whose lines
# all sit at the same depth means all of it — that is how LABELS' closing brace
# and SINGLE_BYTE_INDEXES ended up at column 0 inside `module Encodings`. These
# two blocks keep their indentation with `<<-`.
out << <<-RUBY
    }.freeze

    # For each legacy single-byte encoding, the code point of byte 0x80 + i,
    # or nil where the byte has no mapping.
    SINGLE_BYTE_INDEXES = {
RUBY
indexes.each do |name, index|
  out << "      #{name.inspect} => [\n"
  index.each_slice(8) do |slice|
    out << "        " << slice.map { |cp| cp ? format("0x%04X", cp) : "nil" }.join(", ") << ",\n"
  end
  out << "      ].freeze,\n"
end
out << <<-RUBY
    }.freeze
  end
end
RUBY

target = File.expand_path("../lib/dommy/encodings/tables.rb", __dir__)
File.write(target, out)
puts "wrote #{target}: #{labels.size} labels, #{indexes.size} single-byte indexes"

# --- Multi-byte index overrides ---------------------------------------------

require_relative "../lib/dommy/encodings"

def read_full_index(path)
  File.foreach(path).each_with_object({}) do |line, index|
    next if line.start_with?("#") || line.strip.empty?

    pointer, code_point = line.split("\t")
    index[pointer.to_i] = code_point.hex
  end
end

MULTIBYTE_FILES = {jis0208: "index-jis0208.txt", jis0212: "index-jis0212.txt", big5: "index-big5.txt",
                   euc_kr: "index-euc-kr.txt", gb18030: "index-gb18030.txt"}.freeze

indexes_module = Dommy::Encodings::LegacyIndexes
overrides = {}
nulls = {}
MULTIBYTE_FILES.each do |name, file|
  spec = read_full_index(File.join(dir, file))
  differ = {}
  empty = []
  indexes_module::POINTER_COUNTS.fetch(name).times do |pointer|
    want = spec[pointer]
    next if want == indexes_module.ruby_lookup(name, pointer)

    want ? differ[pointer] = want : empty << pointer
  end
  overrides[name] = differ
  nulls[name] = empty.slice_when { |a, b| b != a + 1 }.map { |run| run.first..run.last }
end

multi = +<<~HEADER
  # frozen_string_literal: true

  # Generated by script/build_encoding_tables.rb from the Encoding Standard's
  # index-{jis0208,jis0212,big5,euc-kr,gb18030}.txt, against the Ruby
  # encodings LegacyIndexes.ruby_lookup reads. Do not edit by hand.
  #
  # Spec: https://encoding.spec.whatwg.org/#indexes

  module Dommy
    module Encodings
      # Pointer => code point, where the spec's index and Ruby's table differ.
      MULTIBYTE_INDEX_OVERRIDES = {
HEADER
overrides.each do |name, table|
  multi << "      #{name}: {\n"
  table.each_slice(6) { |row| multi << "        " << row.map { |p, cp| format("%d => 0x%04X", p, cp) }.join(", ") << ",\n" }
  multi << "      }.freeze,\n"
end
multi << "    }.freeze\n\n"
multi << "    # Pointers Ruby's table maps that the spec's index leaves empty.\n"
multi << "    MULTIBYTE_INDEX_NULLS = {\n"
nulls.each { |name, ranges| multi << "      #{name}: [#{ranges.map { |r| "#{r.first}..#{r.last}" }.join(", ")}].freeze,\n" }
multi << "    }.freeze\n  end\nend\n"

multi_target = File.expand_path("../lib/dommy/encodings/multibyte_overrides.rb", __dir__)
File.write(multi_target, multi)
puts "wrote #{multi_target}: " + overrides.map { |n, t| "#{n} #{t.size} (#{nulls[n].size} null runs)" }.join(", ")
